"""
Stage C — Feature extraction + PyTorch Dataset.

Each keystroke WAV clip -> log-mel spectrogram (1 × 64 × 64 tensor).
Clips must first be generated by isolate.py (data/clips/<key>/*.wav).
"""

import numpy as np
import librosa
import soundfile as sf
import torch
from torch.utils.data import Dataset
from pathlib import Path

from config import (
    PROCESS_SR, N_MELS, N_FFT, HOP_LENGTH,
    IMG_HEIGHT, IMG_WIDTH, KEY_TO_IDX, CLIPS_DIR,
)


def audio_to_melspec(audio, sr=PROCESS_SR):
    """
    Convert a 1-D float32 audio array to a log-mel spectrogram.
    Returns float32 ndarray of shape (1, IMG_HEIGHT, IMG_WIDTH).

    The time axis is zero-padded to IMG_WIDTH; if longer it is truncated.
    Frequency axis = N_MELS = IMG_HEIGHT, so no resize needed there.
    """
    mel = librosa.feature.melspectrogram(
        y=audio, sr=sr,
        n_mels=N_MELS, n_fft=N_FFT, hop_length=HOP_LENGTH,
    )
    log_mel = librosa.power_to_db(mel, ref=np.max)

    # Normalise to [0, 1] per clip
    lo, hi = log_mel.min(), log_mel.max()
    log_mel = (log_mel - lo) / (hi - lo + 1e-8)

    # Fixed-width time axis (pad or truncate)
    T = log_mel.shape[1]
    if T < IMG_WIDTH:
        log_mel = np.pad(log_mel, ((0, 0), (0, IMG_WIDTH - T)))
    else:
        log_mel = log_mel[:, :IMG_WIDTH]

    return log_mel[np.newaxis].astype(np.float32)   # (1, H, W)


class KeystrokeDataset(Dataset):
    """
    Loads all *.wav clips under clips_dir/<key>/*.wav.
    Returns (mel_tensor, label_int) pairs.
    """

    def __init__(self, clips_dir=CLIPS_DIR, transform=None):
        self.transform = transform
        self.samples   = []   # list of (Path, int)
        self.sessions  = []   # parallel list of session names (for LOSO splits)

        clips_dir = Path(clips_dir)
        for key, idx in KEY_TO_IDX.items():
            # Finds both data/clips/<key>/*.wav (flat)
            # and  data/clips/<session>/<key>/*.wav (per-session)
            for wav in sorted(clips_dir.glob(f'**/{key}/*.wav')):
                self.samples.append((wav, idx))
                # <session>/<key>/<file>.wav -> session is two levels up
                self.sessions.append(wav.parent.parent.name)

        if not self.samples:
            raise RuntimeError(
                f'No clips found under {clips_dir}. '
                'Run isolate.py first.'
            )

    def unique_sessions(self):
        from collections import Counter
        return dict(sorted(Counter(self.sessions).items()))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, i):
        path, label = self.samples[i]
        audio, _    = sf.read(str(path))
        if audio.ndim > 1:
            audio = audio[:, 0]
        mel = audio_to_melspec(audio.astype(np.float32))
        x   = torch.from_numpy(mel)
        if self.transform:
            x = self.transform(x)
        return x, label

    def class_counts(self):
        """Returns a dict {key_char: count} for dataset inspection."""
        from collections import Counter
        from config import IDX_TO_KEY
        raw = Counter(label for _, label in self.samples)
        return {IDX_TO_KEY[k]: v for k, v in sorted(raw.items())}
